CREATE INDEX ix_medico_id_especialidad ON medico (id_especialidad);

DROP TABLE IF EXISTS paciente;
CREATE TABLE paciente (
  id_paciente INTEGER PRIMARY KEY,
  dni CHAR(8) NOT NULL UNIQUE,
  nombres TEXT(80) NOT NULL,
  apellidos TEXT(80) NOT NULL,
  fecha_nacimiento TEXT NOT NULL,
  sexo TEXT NOT NULL CHECK (sexo IN ('M','F','O')),
  email VARCHAR(120),
  telefono VARCHAR(20),
  direccion TEXT(160),
  fecha_registro TEXT NOT NULL
);
CREATE INDEX ix_paciente_apellidos ON paciente (apellidos);

DROP TABLE IF EXISTS turno;
CREATE TABLE turno (
  id_turno INTEGER PRIMARY KEY,
  id_medico INTEGER NOT NULL REFERENCES medico (id_medico) ON DELETE CASCADE ON UPDATE CASCADE,
  fecha TEXT NOT NULL,
  hora_inicio TEXT NOT NULL,
  hora_fin TEXT NOT NULL CHECK (hora_fin > hora_inicio),
  consulta TEXT(40) NOT NULL,
  UNIQUE (id_medico, fecha, hora_inicio)
);
CREATE INDEX ix_turno_fecha ON turno (fecha);

DROP TABLE IF EXISTS cita;
CREATE TABLE cita (
  id_cita INTEGER PRIMARY KEY,
  codigo TEXT(12) NOT NULL UNIQUE,
  id_paciente INTEGER NOT NULL REFERENCES paciente (id_paciente) ON DELETE RESTRICT ON UPDATE CASCADE,
  id_turno INTEGER NOT NULL REFERENCES turno (id_turno) ON DELETE CASCADE ON UPDATE CASCADE,
  fecha TEXT NOT NULL,
  hora TEXT NOT NULL,
  estado TEXT NOT NULL CHECK (estado IN ('PROGRAMADA','ATENDIDA','CANCELADA','NO_ASISTIO')),
  motivo TEXT(120) NOT NULL
);
CREATE INDEX ix_cita_id_paciente ON cita (id_paciente);
CREATE INDEX ix_cita_fecha ON cita (fecha);

DROP TABLE IF EXISTS medicamento;
CREATE TABLE medicamento (
  id_medicamento INTEGER PRIMARY KEY,
  codigo TEXT(12) NOT NULL UNIQUE,
  nombre TEXT(80) NOT NULL UNIQUE,
  categoria TEXT(40) NOT NULL,
  presentacion TEXT(60),
  precio_unitario REAL NOT NULL CHECK (precio_unitario > 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0)
);
CREATE INDEX ix_medicamento_categoria ON medicamento (categoria);

DROP TABLE IF EXISTS receta;
CREATE TABLE receta (
  id_receta INTEGER PRIMARY KEY,
  id_cita INTEGER REFERENCES cita (id_cita) ON DELETE SET NULL ON UPDATE CASCADE,
  id_medico INTEGER NOT NULL REFERENCES medico (id_medico) ON DELETE RESTRICT ON UPDATE CASCADE,
  fecha_emision TEXT NOT NULL,
  diagnostico TEXT(120) NOT NULL,
  observaciones TEXT
);
CREATE INDEX ix_receta_id_cita ON receta (id_cita);

DROP TABLE IF EXISTS detalle_receta;
CREATE TABLE detalle_receta (
  id_detalle INTEGER PRIMARY KEY,
  id_receta INTEGER NOT NULL REFERENCES receta (id_receta) ON DELETE CASCADE ON UPDATE CASCADE,
  id_medicamento INTEGER NOT NULL REFERENCES medicamento (id_medicamento) ON DELETE RESTRICT ON UPDATE CASCADE,
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  dosis TEXT(80) NOT NULL,
  duracion_dias INTEGER NOT NULL CHECK (duracion_dias > 0),
  UNIQUE (id_receta, id_medicamento)
);
CREATE INDEX ix_detalle_receta_id_medicamento ON detalle_receta (id_medicamento);


