DROP TABLE IF EXISTS especialidad;
CREATE TABLE especialidad (
  id_especialidad INTEGER PRIMARY KEY,
  codigo TEXT(10) NOT NULL UNIQUE,
  nombre TEXT(60) NOT NULL UNIQUE,
  descripcion TEXT
);
CREATE INDEX ix_especialidad_nombre ON especialidad (nombre);

DROP TABLE IF EXISTS medico;
CREATE TABLE medico (
  id_medico INTEGER PRIMARY KEY,
  dni CHAR(8) NOT NULL UNIQUE,
  nombres TEXT(80) NOT NULL,
  apellidos TEXT(80) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  telefono VARCHAR(20),
  fecha_ingreso TEXT NOT NULL,
  salario REAL NOT NULL CHECK (salario > 0),
  activo INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0,1)),
  id_especialidad INTEGER NOT NULL REFERENCES especialidad (id_especialidad) ON DELETE RESTRICT ON UPDATE CASCADE
